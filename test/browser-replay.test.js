import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import { prepareScenarios } from '../scripts/validation/prepare-scenarios.mjs';
import {
  buildBrowserReplayInput,
  runBrowserReplay
} from '../scripts/validation/browser-replay.mjs';
import { independentReplay } from '../scripts/validation/supplementary-experiments.mjs';
import { SFVSimulationRunner } from '../src/simulation/SFVSimulationRunner.js';
import { SFVCurrentVideoRule } from '../src/rules/SFVCurrentVideoRule.js';

const scenario = JSON.parse(
  fs.readFileSync(new URL('../scenarios/validation/scenario-b1-v1.json', import.meta.url))
);
function browserFixture() {
  const { browser, one } = prepareScenarios({ ...scenario, diagnostics: { abrDecisions: true } });
  const runner = new SFVSimulationRunner({
    dataset: one.content.dataset,
    network: one.network,
    sessions: [
      {
        ruleFactory: () => new SFVCurrentVideoRule(),
        config: { ...one.sessions[0].config, rule: one.sessions[0].abr.config }
      }
    ]
  });
  const sim = runner.run()[0];
  // The synthetic fixture needs the browser-only platform events explicitly;
  // they are not generated by the default exact-boundary DES.
  const activations = [
    sim.events.find(e => e.eventType === 'SESSION_STARTED'),
    ...sim.events.filter(e => e.eventType === 'SWIPE')
  ];
  sim.events.push(
    ...activations.map((event, index) => ({
      eventType: 'PLAYBACK_SLOT_READY',
      videoId: one.content.playlist[index],
      time: event.time,
      triggerDecision: false
    }))
  );
  sim.events.sort((a, b) => a.time - b.time);
  return {
    ...sim,
    requestTerminationSettled: true,
    browserExperiment: {
      profile: { configuration: browser, resolvedNetwork: browser.network },
      cacheIsolation: { mode: 'http-no-store', cacheStorageAvailable: true, deletedEntries: 0 },
      serverNetwork: { profile: structuredClone(browser.network) },
      clockSynchronization: { sampleCount: 1 }
    },
    compactEventLog: {
      events: runner.lastNetworkReport.events
        .filter(e => e.eventType === 'NETWORK_CAPACITY_CHANGED')
        .map(e => ({ eventType: e.eventType, timestampS: e.time }))
    }
  };
}

test('browser replay uses observed actual swipes and rejects stale/incomplete/uncontrolled input', () => {
  const b = browserFixture();
  const { spec } = buildBrowserReplayInput(b);
  assert.deepEqual(
    spec.sessions[0].config.userModel.swipeTimesS,
    b.events.filter(e => e.eventType === 'SWIPE').map(e => e.time)
  );
  assert.equal(
    spec.sessions[0].config.sessionDurationS,
    b.events.find(e => e.eventType === 'SESSION_ENDED').time
  );
  assert.deepEqual(spec.network, b.browserExperiment.profile.resolvedNetwork);
  assert.equal(spec.content.dataset.videos[0].manifestUrl, '/media/v1/manifest-video-only.mpd');
  assert.equal(spec.content.dataset.videos[0].manifestBytes, 2015);
  assert.equal(spec.sessions[0].config.playbackTiming.mode, 'browser-platform-trace');
  for (const change of [
    x => {
      delete x.browserExperiment.cacheIsolation;
    },
    x => {
      x.browserExperiment.serverNetwork.profile.latencyMs += 20;
    },
    x => {
      x.terminationReason = 'simulation_cutoff';
    },
    x => {
      x.browserExperiment.profile.resolvedNetwork = null;
    },
    x => {
      x.browserExperiment.profile.configuration.playlist[0].manifestUrl = '/custom.mpd';
    },
    x => {
      x.events = x.events.filter(e => e.eventType !== 'PLAYBACK_SLOT_READY');
    },
    x => {
      x.requests.find(r => r.resource?.resourceType === 'manifest').bytesDelivered = 999;
    }
  ]) {
    const bad = structuredClone(b);
    change(bad);
    assert.throws(() => buildBrowserReplayInput(bad), /Browser replay input/);
  }
});

test('replay exercises DES and both isolated ABR checks; discrepancies remain visible in the report', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'sfv-browser-replay-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const browser = browserFixture();
  const report = runBrowserReplay(browser, { outputDirectory: directory });
  assert.equal(
    report.status,
    'within-configured-tolerances',
    JSON.stringify(report.checks.filter(c => !c.passed))
  );
  assert.equal(report.browserDecisions.status, 'replay-passed');
  assert.equal(report.simulatedDecisions.status, 'replay-passed');
  assert.ok(fs.existsSync(`${directory}/simulation/ue-0-result.json`));
  const divergent = structuredClone(browser);
  const media = divergent.requests.find(r => r.resource?.resourceType === 'media');
  media.resource.segmentIndex = 91;
  const mismatch = runBrowserReplay(divergent, { outputDirectory: directory });
  assert.equal(mismatch.status, 'review-required');
  assert.ok(mismatch.observationalComparison.unmatchedRequests.length > 0);
});

test('independent DES validates an input with no browser playback timing and still emits mismatch evidence', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'sfv-independent-replay-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const browser = browserFixture();
  browser.events = browser.events.filter(
    e => e.eventType !== 'PLAYBACK_SLOT_READY' && e.eventType !== 'PLAYBACK_POSITION_SAMPLE'
  );
  const { spec } = buildBrowserReplayInput(browser, { useBrowserPlaybackTiming: false });
  assert.equal(Object.hasOwn(spec.sessions[0].config, 'playbackTiming'), false);
  const report = independentReplay(browser, { outputDirectory: directory });
  assert.ok(['accepted', 'review-required'].includes(report.status));
  assert.equal(report.inputContract.browserPlaybackTiming, false);
  assert.equal(
    Object.hasOwn(
      JSON.parse(fs.readFileSync(`${directory}/independent-experiment.json`)).sessions[0].config,
      'playbackTiming'
    ),
    false
  );
});

test('independent causal replay applies a declared timing profile without importing browser trace', t => {
  const directory = fs.mkdtempSync(path.join(os.tmpdir(), 'sfv-independent-causal-'));
  t.after(() => fs.rmSync(directory, { recursive: true, force: true }));
  const browser = browserFixture();
  const timing = JSON.parse(
    fs.readFileSync(new URL('../examples/causal-simple-timing.json', import.meta.url))
  );
  const report = independentReplay(browser, { outputDirectory: directory, causalTiming: timing });
  const input = JSON.parse(
    fs.readFileSync(path.join(directory, 'independent-experiment.json'), 'utf8')
  );
  assert.deepEqual(input.sessions[0].config.playbackTiming, timing);
  assert.equal(report.timingModel, 'causal-simple');
  assert.equal(report.inputContract.browserPlaybackTiming, false);
  assert.throws(
    () =>
      independentReplay(browser, {
        outputDirectory: directory,
        causalTiming: { mode: 'browser-platform-trace' }
      }),
    /playbackTiming|causal-simple/
  );
});
